/* تحقّق صامت وقت التطوير فقط — لا يحظر البناء، فقط يطبع تحذيرًا:
   (أ) تبويب في NAV_IDS بلا سطر في sidebarNav يفتح بلا اسم ولا أيقونة.
   (ب) بلوك صلاة في BLOCK_IDS بلا سطر في routineBlocks يفقد بطاقته في
       شاشة الروتين (يبقى يُحسب في البلوك الزمني والانضباط، فقط بلا مكان
       يُنقر منه هناك).
   (ج) الكتل الست موجودة في routineBlocks بترتيب غير زمني — تحذير فقط،
       كما شرح التعليق أعلى routineBlocks. */
if (typeof process !== "undefined" && process.env?.NODE_ENV !== "production") {
  const warn = (...args) => {
    if (typeof console !== "undefined") console.warn("[life-config]", ...args);
  };

  const navHave = new Set(sidebarNav.map((n) => n.id));
  const navMissing = NAV_IDS.filter((id) => !navHave.has(id));
  if (navMissing.length) warn("تبويبات بلا سطر في sidebarNav:", navMissing);

  const blockKeys = new Set(BLOCK_IDS);
  const routineBlockOrder = routineBlocks.map((b) => b.key).filter((k) => blockKeys.has(k));
  const routineMissing = BLOCK_IDS.filter((id) => !routineBlockOrder.includes(id));
  if (routineMissing.length) warn("بلوكات صلاة بلا سطر في routineBlocks:", routineMissing);

  const chronological = BLOCK_IDS.filter((id) => routineBlockOrder.includes(id));
  const isChronological = routineBlockOrder.every((id, i) => id === chronological[i]);
  if (!isChronological) {
    warn(
      "كتل الصلاة في routineBlocks مرتّبة بترتيب غير زمني — شاشة «اليوم» ستبقى صحيحة، لكن ترتيب البطاقات في شاشة الروتين لن يطابق تسلسل اليوم الفعلي:",
      routineBlockOrder,
    );
  }
}

